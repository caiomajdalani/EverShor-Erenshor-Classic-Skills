        internal static bool Allows(Spell spell)
        {
            if (spell == null) return false;
            if (NativeSpellIds.Contains(spell.Id ?? "")) return true;
            string name = spell.SpellName ?? "";
            return string.Equals(name, "Florablast",
                       StringComparison.OrdinalIgnoreCase) ||
                   string.Equals(name, "Sivakaya's Dismay",
                       StringComparison.OrdinalIgnoreCase) ||
                   string.Equals(name, "Celestial Smite I",
                       StringComparison.OrdinalIgnoreCase) ||
                   name.StartsWith("Vitheo's Sight",
                       StringComparison.OrdinalIgnoreCase);
        }

        internal static bool Allows(Skill skill)
        {
            if (skill == null) return false;
            if (NativeSkillIds.Contains(skill.Id ?? "")) return true;
            string name = skill.SkillName ?? "";
            return string.Equals(name, "Hateful Stance",
                       StringComparison.OrdinalIgnoreCase) ||
                   string.Equals(name, "Stance: Hateful",
                       StringComparison.OrdinalIgnoreCase);
        }
